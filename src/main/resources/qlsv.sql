CREATE DATABASE IF NOT EXISTS qlsv
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE qlsv;

CREATE TABLE IF NOT EXISTS LOP (
    MaLop VARCHAR(10) PRIMARY KEY,
    TenLop VARCHAR(100) NOT NULL,
    KhoaHoc VARCHAR(20) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS SINHVIEN (
    MaSV VARCHAR(10) PRIMARY KEY,
    HoTen VARCHAR(100) NOT NULL,
    NgaySinh DATE,
    GioiTinh ENUM('Nam', 'Nu', 'Khac'),
    Email VARCHAR(100) UNIQUE,
    SoDienThoai VARCHAR(15),
    MaLop VARCHAR(10) NOT NULL,
    
    CONSTRAINT FK_SINHVIEN_LOP
    FOREIGN KEY (MaLop)
    REFERENCES LOP(MaLop)
    ON UPDATE CASCADE
    ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS MONHOC (
    MaMon VARCHAR(10) PRIMARY KEY,
    TenMon VARCHAR(100) NOT NULL,
    SoTinChi INT NOT NULL,
    
    CONSTRAINT CK_SOTINCHI
    CHECK (SoTinChi BETWEEN 1 AND 10)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DIEM (
    MaSV VARCHAR(10) NOT NULL,
    MaMon VARCHAR(10) NOT NULL,
    DiemTongKet DECIMAL(4,2),

    PRIMARY KEY (MaSV, MaMon),
    
    CONSTRAINT FK_DIEM_SINHVIEN
    FOREIGN KEY (MaSV)
    REFERENCES SINHVIEN(MaSV)
    ON UPDATE CASCADE
    ON DELETE RESTRICT,
    
    CONSTRAINT FK_DIEM_MONHOC
    FOREIGN KEY (MaMon)
    REFERENCES MONHOC(MaMon)
    ON UPDATE CASCADE
    ON DELETE RESTRICT,
    
    CONSTRAINT CK_DIEMTONGKET
    CHECK (DiemTongKet BETWEEN 0 AND 10)
) ENGINE=InnoDB;

